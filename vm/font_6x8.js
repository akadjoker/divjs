// Accents drawn on the two rows above a letter.
const ACCENTS = {
  grave: ['.#...', '..#..'],
  acute: ['...#.', '..#..'],
  circumflex: ['..#..', '.#.#.'],
  tilde: ['.##.#', '#..#.'],
  diaeresis: ['.....', '.#.#.']
};

// Lower case letters start on row 2, so the accent takes rows 0-1. Capital
// letters fill rows 0-6: under an accent they are drawn five rows tall
// (their rows 0, 1, 3, 4 and 6) on rows 2-6.
function accented(base, accent)
{
  const rows = G[base];
  const body = base === base.toUpperCase()
    ? [rows[0], rows[1], rows[3], rows[4], rows[6]]
    : base === 'i'
      ? ['.##..', '..#..', '..#..', '..#..', '.###.']
      : rows.slice(2);
  return [...ACCENTS[accent], ...body];
}

function cedilla(base)
{
  const out = G[base].slice(0, 7);
  out[7] = '.##..';
  return out;
}

const LATIN1 = [
  ['ÀÁÂÃÄ', 'A'], ['ÈÉÊË', 'E'], ['ÌÍÎÏ', 'I'], ['ÒÓÔÕÖ', 'O'], ['ÙÚÛÜ', 'U'],
  ['àáâãä', 'a'], ['èéêë', 'e'], ['ìíîï', 'i'], ['òóôõö', 'o'], ['ùúûü', 'u']
];
const ACCENT_ORDER = {
  A: ['grave', 'acute', 'circumflex', 'tilde', 'diaeresis'],
  E: ['grave', 'acute', 'circumflex', 'diaeresis'],
  I: ['grave', 'acute', 'circumflex', 'diaeresis'],
  O: ['grave', 'acute', 'circumflex', 'tilde', 'diaeresis'],
  U: ['grave', 'acute', 'circumflex', 'diaeresis']
};
for (const [chars, base] of LATIN1)
{
  const order = ACCENT_ORDER[base.toUpperCase()];
  [...chars].forEach((ch, i) =>
  {
    G[ch] = accented(base, order[i]);
  });
}
G['Ñ'] = accented('N', 'tilde');
G['ñ'] = accented('n', 'tilde');
G['Ç'] = cedilla('C');
G['ç'] = cedilla('c');

// rows[code * 8 + row] = the row's 6 pixels as bits, leftmost first.
let rows = null;

function build()
{
  rows = new Uint8Array(256 * FONT_6X8_HEIGHT);
  for (const [ch, glyph] of Object.entries(G))
  {
    const code = ch.codePointAt(0);
    glyph.forEach((line, r) =>
    {
      let bits = 0;
      for (let c = 0; c < 5; c++)
      {
        if (line[c] === '#')
        {
          bits |= 0x20 >> c;
        }
      }
      rows[code * FONT_6X8_HEIGHT + r] = bits;
    });
  }
  return rows;
}

const QUESTION = 63;

// The code drawn for a character: itself when the font has it, "?" for
// anything else printable (control codes stay blank).
export function font6x8Code(code)
{
  const n = Number(code) || 0;
  if (n < 32 || (n >= 127 && n < 160))
  {
    return 0;
  }
  if (n > 255 || !Object.prototype.hasOwnProperty.call(G, String.fromCharCode(n)))
  {
    return QUESTION;
  }
  return n;
}

// True when the pixel at (col, row) of character `code` is set.
export function font6x8Pixel(code, col, row)
{
  const table = rows || build();
  if (col < 0 || col >= FONT_6X8_WIDTH || row < 0 || row >= FONT_6X8_HEIGHT)
  {
    return false;
  }
  const c = font6x8Code(code);
  return (table[c * FONT_6X8_HEIGHT + row] & (0x20 >> col)) !== 0;
}
